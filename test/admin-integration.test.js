import { test, after } from 'node:test';
import assert from 'node:assert/strict';
import { mkdtemp, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
const dir = await mkdtemp(join(tmpdir(), 'fish-admin-integration-'));
process.env.DATA_DIR = dir;
process.env.CONFIG_PATH = join(dir, 'none.json');
process.env.ADMIN_TOKEN = 'isolated-integration-admin-token';
process.env.ADMIN_PORT = '0';
process.env.DEEPSEEK_API_KEY = '';
process.env.IMAGE_API_KEY = '';
const { startPlatform } = await import('../src/platform/runtime.js');
const { dispatch } = await import('../src/dispatch/dispatcher.js');
const { register } = await import('../src/dispatch/registry.js');
let handled = 0;
register({ name: 'test-handler', match: () => true, handle: () => { handled++; } });
let platform = await startPlatform({ schedule: false });
const headers = { Authorization: `Bearer ${process.env.ADMIN_TOKEN}`, 'Content-Type': 'application/json' };
const request = (path, method = 'GET', body) => fetch(`http://127.0.0.1:${platform.management.port}${path}`, { method, headers, ...(body ? { body: JSON.stringify(body) } : {}) });
after(async () => { await platform.stop(); await rm(dir, { recursive: true, force: true }); });

test('静态页面、真实 API 与完整新事件收件闭环', async () => {
  const page = await request('/');
  assert.equal(page.status, 200);
  assert.match(await page.text(), /管理台/);
  assert.equal((await request('/app.js')).status, 200);
  const status = await (await request('/api/status')).json();
  assert.equal(status.connection.connected, false);
  assert.equal(status.usage.today.calls, 0);
  assert.equal(status.scheduler.jobs, 2);
  await dispatch({ post_type: 'request', request_type: 'friend', user_id: 123, flag: 'never-auto-approve', comment: 'hello' });
  await dispatch({ post_type: 'message', message_type: 'private', user_id: 123, message_id: 1, time: 1800000000, message: [{ type: 'record', data: { file: 'voice.silk' } }] });
  const inbox = await (await request('/api/events')).json();
  assert.equal(inbox.items.length, 2);
  assert.equal(inbox.items[0].handling, 'received_only');
  assert.equal(handled, 0);
});
test('角色修改实际阻断触发器但保留事件；配置和任务经 API 保存、重启恢复', async () => {
  assert.equal((await request('/api/users/123', 'PUT', { role: 'blocked', note: 'test' })).status, 200);
  const event = { post_type: 'message', message_type: 'private', user_id: 123, message_id: 2, time: 1800000000, message: [{ type: 'text', data: { text: 'ping' } }] };
  await dispatch(event);
  assert.equal(handled, 0);
  const inbox = await (await request('/api/events')).json();
  assert.equal(inbox.items[0].handling, 'blocked');
  const settings = await (await request('/api/config')).json();
  settings.policy.features.draw = false;
  assert.equal((await request('/api/config', 'PUT', settings)).status, 200);
  const job = await (await request('/api/jobs', 'POST', { name: '人工维护', type: 'maintenance', enabled: false, schedule: { kind: 'interval', everyMs: 60000 } })).json();
  assert.ok(job.id);
  await platform.stop();
  platform = await startPlatform({ schedule: false });
  const restored = await (await request('/api/config')).json();
  assert.equal(restored.policy.features.draw, false);
  assert.ok((await (await request('/api/jobs')).json()).items.some((row) => row.id === job.id));
  await dispatch(event);
  assert.equal(handled, 0);
  await request('/api/users/123', 'DELETE');
  await dispatch(event);
  assert.equal(handled, 1);
  assert.equal((await request(`/api/jobs/${job.id}`, 'DELETE')).status, 200);
  const logs = await (await request('/api/logs')).json();
  assert.ok(logs.items.some((row) => row.message.includes('[admin]')));
  assert.ok(!JSON.stringify(logs).includes(process.env.ADMIN_TOKEN));
});
